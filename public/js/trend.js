        function applyColorChange() {
            const growthCells = document.querySelectorAll("#Locality_List tbody tr td:nth-child(5), #Project_List tbody tr td:nth-child(5)");
            growthCells.forEach(cell => {
                const value = parseFloat(cell.textContent);
                if (value < 0) {
                    cell.style.color = "red";
                } else {
                    cell.style.color = "green";
                }
            });
        }

        function sortTable(criteria, table) {
            const rows = Array.from(table.rows);

            rows.sort((a, b) => {
                const aValue = getCellValue(a, criteria);
                const bValue = getCellValue(b, criteria);

                if (criteria === "demand" || criteria === "price" || criteria === "growth") {
                    return bValue - aValue;
                }
                return aValue.localeCompare(bValue);
            });

            rows.forEach(row => table.appendChild(row));
        }

        function getCellValue(row, criteria) {
            switch (criteria) {
                case "demand":
                    return row.cells[5].textContent === "High" ? 3 : row.cells[5].textContent === "Medium" ? 2 : 1;
                case "price":
                    return parseFloat(row.cells[3].textContent.replace(/[^0-9.-]+/g, ""));
                case "growth":
                    return parseFloat(row.cells[4].textContent.replace(/[^0-9.-]+/g, ""));
                default:
                    return row.cells[0].textContent;
            }
        }

